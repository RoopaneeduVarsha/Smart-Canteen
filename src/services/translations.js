// Helper: Translate Menu Item Name
export function tItemName(itemOrName, lang = 'en') {
  if (!itemOrName) return '';
  const name = typeof itemOrName === 'object' ? itemOrName.name : itemOrName;
  if (!name || lang === 'en') return name;

  const translation = MENU_ITEM_TRANSLATIONS[name];
  if (translation && translation[lang]) {
    return translation[lang];
  }
  return name;
}

// Helper: Translate Menu Item Description
export function tItemDesc(itemOrDesc, lang = 'en') {
  if (!itemOrDesc) return '';
  let desc = typeof itemOrDesc === 'object' ? itemOrDesc.description : itemOrDesc;
  const name = typeof itemOrDesc === 'object' ? itemOrDesc.name : null;

  if (lang === 'en') return desc || '';

  if (name && MENU_ITEM_TRANSLATIONS[name]) {
    const descKey = `desc_${lang}`;
    if (MENU_ITEM_TRANSLATIONS[name][descKey]) {
      return MENU_ITEM_TRANSLATIONS[name][descKey];
    }
  }

  // Check by exact description match
  for (const itemKey of Object.keys(MENU_ITEM_TRANSLATIONS)) {
    const entry = MENU_ITEM_TRANSLATIONS[itemKey];
    if (entry && entry[`desc_${lang}`]) {
      // If the English name was passed as item
      if (itemKey === desc) return entry[`desc_${lang}`];
    }
  }

  return desc || '';
}

// Helper: Translate Category Name
export function tCategoryName(catOrName, lang = 'en') {
  if (!catOrName) return '';
  const name = typeof catOrName === 'object' ? (catOrName.name || catOrName.id) : catOrName;
  if (!name || lang === 'en') return name;

  const translation = CATEGORY_TRANSLATIONS[name];
  if (translation && translation[lang]) {
    return translation[lang];
  }
  return name;
}
